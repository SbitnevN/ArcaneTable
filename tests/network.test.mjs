test('Access tokens persist hashed, enforce expiry, claims and revocation', () => {
  const directory = mkdtempSync(join(tmpdir(), 'arcane-access-'));
  const originalNow = Date.now;
  try {
    const access = new Access(directory);
    const a = access.create('player', 'Игрок А', 1, 'project');
    const b = access.create('player', 'Игрок Б', 1, 'project');
    assert.ok(!readFileSync(join(directory, 'access.json'), 'utf8').includes(a.token));
    access.claim(a.id, 'tarkhun', 'Алиса');
    assert.throws(() => access.claim(b.id, 'tarkhun', 'Боб'));
    const restored = new Access(directory);
    assert.equal(restored.resolve(a.token).id, a.id);
    assert.equal(restored.find(a.id).characterId, 'tarkhun');
    restored.release(a.id); restored.claim(b.id, 'tarkhun', 'Боб');
    restored.revoke(b.id); assert.equal(restored.resolve(b.token), null);
    assert.ok(!JSON.stringify(restored.list()).includes('hash'));
    Date.now = () => originalNow() + 3600001;
    assert.equal(restored.resolve(a.token), null);
  } finally { Date.now = originalNow; rmSync(directory, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 }); }
});

test('LAN role links, player commands, realtime privacy, reconnect and revocation work end to end', async t => {
  const directory = mkdtempSync(join(tmpdir(), 'arcane-lan-'));
  const service = await createService(directory, { staticRoot: resolve('dist') });
  const server = createServer((req, res) => { void service.handle(req, res, () => { res.writeHead(404); res.end(); }); });
  service.attach(server); await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const origin = `http://127.0.0.1:${server.address().port}`;
  const rootHeaders = { Cookie: `arcane=${service.master}`, Origin: origin, 'Content-Type': 'application/json' };
  const sockets = [];
  const rootPost = async (path, body) => { const response = await fetch(origin + path, { method: 'POST', headers: rootHeaders, body: JSON.stringify(body) }); assert.equal(response.status, 200, await response.clone().text()); return response.json(); };
  try {
    let network = await (await fetch(origin + '/api/network', { headers: rootHeaders })).json();
    if (!network.interfaces.length) { t.skip('No private IPv4 adapter available'); return; }
    network = await rootPost('/api/network', { enabled: true, address: network.interfaces[0].address });
    assert.equal(network.enabled, true);
    assert.equal((await fetch(network.url)).status, 200);
    const projectId = service.store.state().activeId;
    service.store.execute({ id: randomUUID(), type: 'project.create', name: 'СКРЫТАЯ КАМПАНИЯ' });
    service.store.execute({ id: randomUUID(), type: 'project.live', projectId });
    const create = async (role, label) => rootPost('/api/connections/create', { role, label, hours: 1, projectId });
    const a = await create('player', 'А'); const b = await create('player', 'Б'); const dm = await create('master', 'DM');
    const token = new URL(a.link).searchParams.get('join');
    const secondToken = new URL(b.link).searchParams.get('join');
    const dmToken = new URL(dm.link).searchParams.get('join');
    const auth = { Authorization: `Bearer ${token}`, Origin: network.url, 'Content-Type': 'application/json' };
    const session = await fetch(network.url + '/api/session?token=' + token);
    assert.equal(session.status, 200); assert.equal((await session.json()).role, 'player');
    assert.equal((await fetch(network.url + '/api/state', { headers: auth })).status, 403);
    assert.equal((await fetch(network.url + '/api/network', { headers: { Authorization: `Bearer ${dmToken}` } })).status, 403);
    assert.equal((await fetch(network.url + '/api/state', { headers: { Authorization: `Bearer ${dmToken}` } })).status, 200);
    const initial = await (await fetch(network.url + '/api/player', { headers: auth })).json();
    assert.equal(initial.own, null); assert.ok(!JSON.stringify(initial).includes('СКРЫТАЯ'));
    assert.ok(!JSON.stringify(initial).includes('blocks'));
    const claim = await fetch(network.url + '/api/player/claim', { method: 'POST', headers: auth, body: JSON.stringify({ characterId: 'paladin', name: 'Алиса' }) });
    assert.equal(claim.status, 200); assert.equal((await claim.json()).own.characterId, 'paladin');
    const occupied = await fetch(network.url + '/api/player/claim', { method: 'POST', headers: { ...auth, Authorization: `Bearer ${secondToken}` }, body: JSON.stringify({ characterId: 'paladin', name: 'Боб' }) });
    assert.equal(occupied.status, 400);
    const ws = new WebSocket(network.url.replace('http:', 'ws:') + '/realtime?access=' + token, { origin: network.url }); sockets.push(ws);
    const first = await new Promise((resolve, reject) => { ws.once('message', bytes => resolve(JSON.parse(String(bytes)))); ws.once('error', reject); });
    assert.equal(first.type, 'player'); assert.equal(first.view.own.characterId, 'paladin');
    assert.ok(!JSON.stringify(first).includes('Тайна Тархуна'));
    const update = new Promise(resolve => ws.once('message', bytes => resolve(JSON.parse(String(bytes)))));
    const id = randomUUID();
    const payload = { id, type: 'player.update', hp: 7, projectId: 'bad', characterId: 'tarkhun', maxHp: 999 };
    const apply = () => fetch(network.url + '/api/player/command', { method: 'POST', headers: auth, body: JSON.stringify(payload) });
    assert.equal((await apply()).status, 200);
    const event = await update; assert.equal(event.view.own.game.hp, 7); assert.equal(event.view.own.game.maxHp, 10);
    const revision = service.store.state().revision; await apply(); assert.equal(service.store.state().revision, revision);
    const stored = service.store.state().projects.find(p => p.id === projectId);
    assert.equal(stored.games.tarkhun.hp, 28);
    assert.equal(stored.games.paladin.hp, 7);
    const reconnect = await (await fetch(network.url + '/api/player', { headers: auth })).json();
    assert.equal(reconnect.own.game.hp, 7);
    const sheetEdit = await fetch(network.url + '/api/player/command', { method: 'POST', headers: auth, body: JSON.stringify({ id: randomUUID(), type: 'player.update', sheet: { inventory: 'Верёвка', spells: ['bless'], race: 'Эльф', maxHp: 999, lssOriginal: { altered: true } } }) });
    assert.equal(sheetEdit.status, 200); const sheetView = await sheetEdit.json(); assert.equal(sheetView.own.game.inventory, 'Верёвка'); assert.equal(sheetView.own.game.race, 'Эльф'); assert.equal(sheetView.own.game.maxHp, 10); assert.equal(sheetView.own.game.lssOriginal, undefined);
    const run = (type, extra = {}) => service.store.execute({ id: randomUUID(), type, projectId, ...extra });
    run('combat.create', { name: 'Проверка с телефона' }); run('combat.add', { characterId: 'paladin' }); run('combat.add', { participant: { name: 'Гоблин', maxHp: 357, ac: 53 } });
    const encounter = service.store.state().projects.find(p => p.id === projectId).combat;
    const hero = encounter.participants.find(p => p.characterId === 'paladin'); const enemy = encounter.participants.find(p => p.side === 'enemy');
    run('combat.start'); run('combat.active', { participantId: hero.id }); run('combat.mode', { approval: true });
    const actionId = randomUUID();
    const action = { id: actionId, type: 'player.action', targetId: enemy.id, kind: 'damage', amount: 12 };
    const pending = await fetch(network.url + '/api/player/command', { method: 'POST', headers: auth, body: JSON.stringify(action) });
    assert.equal(pending.status, 200); const pendingView = await pending.json(); assert.equal(pendingView.pendingAction, true);
    assert.ok(!Object.hasOwn(pendingView.combat.participants.find(p => p.id === enemy.id), 'hp'));
    assert.ok(!Object.hasOwn(pendingView.combat.participants.find(p => p.id === enemy.id), 'ac'));
    assert.equal(service.store.state().projects.find(p => p.id === projectId).combat.participants.find(p => p.id === enemy.id).hp, 357);
    await rootPost('/api/command', { id: randomUUID(), type: 'combat.approve', projectId, requestId: actionId });
    assert.equal(service.store.state().projects.find(p => p.id === projectId).combat.participants.find(p => p.id === enemy.id).hp, 345);
    const approved = await (await fetch(network.url + '/api/player', { headers: auth })).json(); assert.equal(approved.pendingAction, false);
    assert.ok(!Object.hasOwn(approved.combat, 'history'));
    run('combat.add', { characterId: 'tarkhun' }); run('combat.mode', { approval: false });
    const ally = service.store.state().projects.find(p => p.id === projectId).combat.participants.find(p => p.characterId === 'tarkhun');
    const friendly = await fetch(network.url + '/api/player/command', { method: 'POST', headers: auth, body: JSON.stringify({ id: randomUUID(), type: 'player.action', targetId: ally.id, kind: 'damage', amount: 2 }) });
    assert.equal(friendly.status, 200); assert.equal((await friendly.json()).combat.participants.find(p => p.id === ally.id).hp, 26);
    run('combat.active', { participantId: enemy.id });
    const outOfTurn = await fetch(network.url + '/api/player/command', { method: 'POST', headers: auth, body: JSON.stringify({ id: randomUUID(), type: 'player.action', targetId: ally.id, kind: 'damage', amount: 2 }) });
    assert.equal(outOfTurn.status, 400); assert.equal(service.store.state().projects.find(p => p.id === projectId).games.tarkhun.hp, 26);
    const connectionId = a.connections.find(item => item.label === 'А').id;
    await rootPost('/api/connections/revoke', { id: connectionId });
    assert.equal((await fetch(network.url + '/api/player', { headers: auth })).status, 401);
    assert.equal((await fetch(origin + '/api/state', { headers: { ...rootHeaders, Authorization: `Bearer ${token}` } })).status, 401);
    const newClaim = await fetch(network.url + '/api/player/claim', { method: 'POST', headers: { ...auth, Authorization: `Bearer ${secondToken}` }, body: JSON.stringify({ characterId: 'paladin', name: 'Боб' }) });
    assert.equal(newClaim.status, 200);
    await rootPost('/api/network', { enabled: false });
    assert.equal((await (await fetch(origin + '/api/network', { headers: rootHeaders })).json()).enabled, false);
  } finally { for (const ws of sockets) ws.terminate(); service.close(); await new Promise(resolve => server.close(resolve)); rmSync(directory, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 }); }
});
